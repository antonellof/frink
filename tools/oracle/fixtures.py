#!/usr/bin/env python3
"""Regenerates every synthetic fixture from its script, in place.

    tools/oracle/fixtures.py <llama.cpp-src>

`tools/oracle/fixtures.tsv` names, for each GGUF under
`crates/frink-models/tests/fixtures/`, the outcome `frink parity`
must reach on it (read by `tools/oracle/parity.py`) and the script
invocation that writes it (`OUT` is the fixture's own path). The
scripts import llama.cpp's own `gguf-py` from <llama.cpp-src>, so a
fixture is regenerated by the writer of the commit under test. The
caller runs `git diff --exit-code` afterwards: a fixture that is not
what its script writes fails.

A recipe of `-` is a fixture this cannot rebuild, and the row says why
in its comment. Those are named, not skipped silently.
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FIXTURES = os.path.join(ROOT, "crates/frink-models/tests/fixtures")
MANIFEST = os.path.join(ROOT, "tools/oracle/fixtures.tsv")


def rows():
    with open(MANIFEST) as f:
        for line in f:
            body = line.split("#", 1)[0].split()
            if body:
                yield body[0], body[2:]


def main():
    src = os.path.abspath(sys.argv[1])
    env = dict(os.environ, PYTHONPATH=os.path.join(src, "gguf-py"))
    failed = 0
    for name, recipe in rows():
        if recipe == ["-"]:
            print(f"fixture -       {name} (no recipe, see fixtures.tsv)")
            continue
        script, args = recipe[0], recipe[1:]
        out = os.path.join(FIXTURES, name + ".gguf")
        args = [out if a == "OUT" else a for a in args]
        r = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", script)] + args,
                           env=env, capture_output=True, text=True)
        if r.returncode != 0:
            failed += 1
            tail = (r.stderr.strip().splitlines() or ["?"])[-1]
            print(f"fixture FAILED  {name}: {tail}")
        else:
            print(f"fixture written {name}", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
